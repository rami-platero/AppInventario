-- AppInventario: esquema de la base inventariodb.
-- Ejecutar una sola vez en pgAdmin4: Query Tool, con auto-commit activado.
-- JPA nunca crea ni modifica tablas: schema-generation esta en "none".

CREATE TABLE categoria (
    idcategoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(45) NOT NULL,
    CONSTRAINT categoria_nombre_unico UNIQUE (nombre)
);

CREATE TABLE proveedor (
    idproveedor INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(45) NOT NULL,
    telefono VARCHAR(20),
    email VARCHAR(60),
    CONSTRAINT proveedor_nombre_unico UNIQUE (nombre)
);

CREATE TABLE producto (
    idproducto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(60) NOT NULL,
    descripcion VARCHAR(200),
    unidad VARCHAR(15) NOT NULL DEFAULT 'unidad',
    stock INT NOT NULL DEFAULT 0,
    stock_minimo INT NOT NULL DEFAULT 0,
    precio NUMERIC(12,2) NOT NULL DEFAULT 0,
    perecedero BOOLEAN NOT NULL DEFAULT FALSE,
    categoria_idcategoria INT NOT NULL,
    CONSTRAINT producto_codigo_unico UNIQUE (codigo),
    CONSTRAINT producto_stock_no_negativo CHECK (stock >= 0),
    CONSTRAINT producto_minimo_no_negativo CHECK (stock_minimo >= 0),
    CONSTRAINT producto_precio_no_negativo CHECK (precio >= 0),
    CONSTRAINT producto_categoria_fk FOREIGN KEY (categoria_idcategoria)
        REFERENCES categoria (idcategoria)
);

CREATE TABLE producto_proveedor (
    producto_idproducto INT NOT NULL,
    proveedor_idproveedor INT NOT NULL,
    precio_compra NUMERIC(12,2) NOT NULL DEFAULT 0,
    dias_entrega INT,
    codigo_proveedor VARCHAR(30),
    CONSTRAINT producto_proveedor_pk PRIMARY KEY (producto_idproducto, proveedor_idproveedor),
    CONSTRAINT producto_proveedor_producto_fk FOREIGN KEY (producto_idproducto)
        REFERENCES producto (idproducto),
    CONSTRAINT producto_proveedor_proveedor_fk FOREIGN KEY (proveedor_idproveedor)
        REFERENCES proveedor (idproveedor),
    CONSTRAINT producto_proveedor_precio_no_negativo CHECK (precio_compra >= 0),
    CONSTRAINT producto_proveedor_dias_no_negativo CHECK (dias_entrega IS NULL OR dias_entrega >= 0)
);

CREATE TABLE lote (
    idlote INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_idproducto INT NOT NULL,
    codigo VARCHAR(30),
    vencimiento DATE NOT NULL,
    cantidad INT NOT NULL DEFAULT 0,
    CONSTRAINT lote_producto_fk FOREIGN KEY (producto_idproducto)
        REFERENCES producto (idproducto),
    CONSTRAINT lote_cantidad_no_negativa CHECK (cantidad >= 0)
);

CREATE TABLE movimiento_stock (
    idmovimiento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_idproducto INT NOT NULL,
    proveedor_idproveedor INT,
    lote_idlote INT,
    tipo VARCHAR(10) NOT NULL,
    cantidad INT NOT NULL,
    stock_resultante INT NOT NULL,
    motivo VARCHAR(200),
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT movimiento_producto_fk FOREIGN KEY (producto_idproducto)
        REFERENCES producto (idproducto),
    CONSTRAINT movimiento_proveedor_fk FOREIGN KEY (proveedor_idproveedor)
        REFERENCES proveedor (idproveedor),
    CONSTRAINT movimiento_lote_fk FOREIGN KEY (lote_idlote)
        REFERENCES lote (idlote),
    CONSTRAINT movimiento_tipo_valido CHECK (tipo IN ('ENTRADA', 'SALIDA', 'AJUSTE')),
    CONSTRAINT movimiento_cantidad_no_negativa CHECK (cantidad >= 0),
    CONSTRAINT movimiento_resultante_no_negativo CHECK (stock_resultante >= 0)
);

CREATE INDEX producto_categoria_idx ON producto (categoria_idcategoria);
CREATE INDEX movimiento_producto_idx ON movimiento_stock (producto_idproducto);
CREATE INDEX movimiento_fecha_idx ON movimiento_stock (fecha DESC);
CREATE INDEX lote_producto_idx ON lote (producto_idproducto);
CREATE INDEX lote_vencimiento_idx ON lote (vencimiento);
CREATE UNIQUE INDEX lote_unico ON lote (producto_idproducto, vencimiento, COALESCE(codigo, ''));
