-- AppInventario: multi-negocio, usuarios y roles.
-- Ejecutar DESPUES de 03_lotes.sql. Usa CREATE y ALTER, no recrea tablas con datos.
--
-- Cada negocio ve unicamente sus propios datos. Las tablas categoria, proveedor,
-- producto y movimiento_stock pasan a tener una columna negocio_idnegocio, y la
-- unicidad de nombre/codigo que antes era global ahora es por negocio: dos
-- negocios distintos pueden tener cada uno su propia categoria "Almacen".
--
-- Como ya hay datos cargados, el negocio_idnegocio se agrega nullable, se
-- completa para las filas existentes con un negocio por defecto, y recien
-- despues se pone NOT NULL.
--
-- Es idempotente a proposito (IF NOT EXISTS, DROP ... IF EXISTS antes de cada
-- ADD CONSTRAINT): sirve tanto para la primera vez como para volver a correrlo
-- despues de sql/00_reiniciar_datos.sql.

CREATE TABLE IF NOT EXISTS usuario (
    idusuario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(80) NOT NULL,
    password_hash VARCHAR(64) NOT NULL,
    nombre VARCHAR(60) NOT NULL,
    CONSTRAINT usuario_email_unico UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS negocio (
    idnegocio INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS membresia (
    usuario_idusuario INT NOT NULL,
    negocio_idnegocio INT NOT NULL,
    rol VARCHAR(12) NOT NULL,
    CONSTRAINT membresia_pk PRIMARY KEY (usuario_idusuario, negocio_idnegocio),
    CONSTRAINT membresia_usuario_fk FOREIGN KEY (usuario_idusuario)
        REFERENCES usuario (idusuario),
    CONSTRAINT membresia_negocio_fk FOREIGN KEY (negocio_idnegocio)
        REFERENCES negocio (idnegocio),
    CONSTRAINT membresia_rol_valido CHECK (rol IN ('PROPIETARIO', 'EMPLEADO'))
);

ALTER TABLE categoria ADD COLUMN IF NOT EXISTS negocio_idnegocio INT;
ALTER TABLE proveedor ADD COLUMN IF NOT EXISTS negocio_idnegocio INT;
ALTER TABLE producto ADD COLUMN IF NOT EXISTS negocio_idnegocio INT;
ALTER TABLE movimiento_stock ADD COLUMN IF NOT EXISTS negocio_idnegocio INT;

